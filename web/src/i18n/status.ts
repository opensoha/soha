export function formatStatusLabel(value: string | null | undefined, localeCode: LocaleCode) {
  const normalizedValue = value?.trim() || '-'
  const key = normalizedValue.toLowerCase().replace(/[\s_-]+/g, '')
  const label = statusLabels[key]
  if (!label) return normalizedValue
  return localeCode === 'zh_CN' ? label.zh : label.en
}
